/**
 * Persistent orchestrator state and workspace layout.
 *
 * Layout (relative to the repo root the CLI runs in):
 *
 *   .agentspec/
 *   ├── .gitignore            # "*" — run artifacts never enter git
 *   ├── state.json            # per-issue attempts / branch / last run / blocked
 *   ├── issues/<n>/BRIEF.md   # produced by `intake`
 *   └── runs/<iso>/           # events.jsonl + gates.json + pr-body.md + reports
 *
 * `.worktrees/` (created by `deliver`) gets the same self-ignoring `.gitignore`
 * so agent runs never dirty the repository root. We deliberately do NOT touch
 * the repository's own `.gitignore` (owned by the packaging slice): a nested
 * `.gitignore` containing `*` keeps `git status --short` clean.
 */

import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join } from "node:path";

export const STATE_VERSION = 1;

export function stateDir(cwd) {
  return join(cwd, ".agentspec");
}

export function stateFile(cwd) {
  return join(cwd, ".agentspec", "state.json");
}

export function runsDir(cwd) {
  return join(cwd, ".agentspec", "runs");
}

export function issueArtifactDir(cwd, number) {
  return join(cwd, ".agentspec", "issues", String(number));
}

/** Create `.agentspec/` plus its self-ignoring `.gitignore`. */
export async function ensureStateRoot(cwd) {
  const root = stateDir(cwd);
  await mkdir(join(root, "runs"), { recursive: true });
  await mkdir(join(root, "issues"), { recursive: true });
  await ensureDirWithSelfIgnore(root);
  return root;
}

/** mkdir -p + write a `*` .gitignore into the directory if it has none. */
export async function ensureDirWithSelfIgnore(dir) {
  await mkdir(dir, { recursive: true });
  const ignore = join(dir, ".gitignore");
  if (!existsSync(ignore)) {
    await writeFile(ignore, "# generated by mocl-agent — local run artifacts, never committed\n*\n", "utf8");
  }
}

/** @returns {Promise<{version:number, updatedAt:string|null, issues:Record<string, any>}>} */
export async function readState(cwd) {
  try {
    const raw = await readFile(stateFile(cwd), "utf8");
    const parsed = JSON.parse(raw);
    return {
      version: parsed.version ?? STATE_VERSION,
      updatedAt: parsed.updatedAt ?? null,
      issues: parsed.issues ?? {},
    };
  } catch (error) {
    if (error?.code === "ENOENT") return { version: STATE_VERSION, updatedAt: null, issues: {} };
    if (error instanceof SyntaxError) return { version: STATE_VERSION, updatedAt: null, issues: {} };
    throw error;
  }
}

/**
 * Atomic state write (tmp + rename). The tmp name is unique per write because
 * `watch` can have several deliveries finishing at the same time.
 */
export async function writeState(cwd, state, now = new Date()) {
  await ensureStateRoot(cwd);
  const file = stateFile(cwd);
  const payload = {
    version: STATE_VERSION,
    updatedAt: now.toISOString(),
    issues: state.issues ?? {},
  };
  const tmp = `${file}.${process.pid}.${Date.now().toString(36)}.${Math.random().toString(36).slice(2)}.tmp`;
  await writeFile(tmp, `${JSON.stringify(payload, null, 2)}\n`, "utf8");
  await rename(tmp, file);
  return payload;
}

/**
 * Serialise read-modify-write cycles on `state.json` within this process.
 * (Cross-process concurrency is out of scope: one orchestrator per workspace.)
 */
const stateLocks = new Map();

export function withStateLock(cwd, fn) {
  const key = stateFile(cwd);
  const previous = stateLocks.get(key) ?? Promise.resolve();
  const run = previous.catch(() => undefined).then(() => fn());
  stateLocks.set(
    key,
    run.catch(() => undefined),
  );
  return run;
}

export function issueState(state, number) {
  return state.issues[String(number)] ?? null;
}

export function attemptsOf(state, number) {
  return Number(state.issues[String(number)]?.attempts ?? 0);
}

export function isBlockedInState(state, number) {
  return state.issues[String(number)]?.blocked === true;
}

/** Merge `patch` into the per-issue state entry and persist it (lock-serialised). */
export async function updateIssueState(cwd, number, patch, now = new Date()) {
  return withStateLock(cwd, async () => {
    const state = await readState(cwd);
    const key = String(number);
    const current = state.issues[key] ?? { number, attempts: 0 };
    state.issues[key] = { ...current, number, ...patch, updatedAt: now.toISOString() };
    await writeState(cwd, state, now);
    return state.issues[key];
  });
}

/** Write an artifact inside a run directory (`mkdir -p` + utf8 file). */
export async function writeRunFile(dir, name, content) {
  await mkdir(dir, { recursive: true });
  const target = join(dir, name);
  await writeFile(target, String(content ?? ""), "utf8");
  return target;
}

export async function writeIssueFile(cwd, number, name, content) {
  const dir = issueArtifactDir(cwd, number);
  await ensureDirWithSelfIgnore(join(cwd, ".agentspec", "issues"));
  await mkdir(dir, { recursive: true });
  const target = join(dir, name);
  await writeFile(target, String(content ?? ""), "utf8");
  return target;
}
